def youtube_chat_worker(video_id: str) -> None:
    global chat_status
    if not PYTCHAT_AVAILABLE:
        chat_status = ("DEMO MODE (pip install pytchat)", "demo")
        return
    if not video_id:
        chat_status = ("DEMO MODE (no video ID set)", "demo")
        return

    last_spawn: dict[str, float] = {}
    while not stop_event.is_set():
        try:
            # interruptable=False is REQUIRED when pytchat runs outside the
            # main thread, otherwise it crashes ("signal only works in main thread")
            chat = pytchat.create(video_id=video_id, interruptable=False)
            chat_status = ("LIVE: YouTube chat connected", "ok")
            while chat.is_alive() and not stop_event.is_set():
                for c in chat.get().sync_items():
                    word = parse_attack(c.message or "")
                    if not word:
                        continue
                    uid = getattr(c.author, "channelId", c.author.name)
                    now = time.time()
                    if now - last_spawn.get(uid, 0) < VIEWER_COOLDOWN:
                        continue
                    last_spawn[uid] = now
                    if chat_queue.qsize() < MAX_PENDING:
                        chat_queue.put({"word": word, "sender": clean_name(c.author.name)})
                time.sleep(0.1)
            chat_status = ("Chat ended - retrying...", "warn")
        except Exception as exc:  # network / bad video id
            print(f"[pytchat] {exc}")
            chat_status = ("Chat error - retrying (check ID)", "err")
        stop_event.wait(8)


