SR = 22050


def _synth(dur, freq_fn, vol, wave="sine", decay=3.0, attack=0.004):
    n = max(1, int(SR * dur))
    out = [0.0] * n
    phase = 0.0
    two_pi = 2 * math.pi
    for i in range(n):
        p = i / n
        t = i / SR
        phase += freq_fn(p) / SR
        ph = phase % 1.0
        if wave == "sine":
            s = math.sin(two_pi * ph)
        elif wave == "square":
            s = 1.0 if ph < 0.5 else -1.0
        elif wave == "saw":
            s = 2 * ph - 1
        elif wave == "tri":
            s = 4 * abs(ph - 0.5) - 1
        else:
            s = random.uniform(-1, 1)
        env = (t / attack if t < attack else 1.0) * math.exp(-decay * p)
        out[i] = s * env * vol
    return out


def _noise(dur, vol, decay=4.0, cut_a=0.4, cut_b=0.03):
    n = max(1, int(SR * dur))
    out = [0.0] * n
    lp = 0.0
    for i in range(n):
        p = i / n
        lp += (random.uniform(-1, 1) - lp) * (cut_a + (cut_b - cut_a) * p)
        out[i] = lp * math.exp(-decay * p) * vol * 2.0
    return out


def _mix(*tracks):
    n = max(len(t) for t in tracks)
    out = [0.0] * n
    for t in tracks:
        for i, v in enumerate(t):
            out[i] += v
    return out


def _cat(*tracks):
    out = []
    for t in tracks:
        out.extend(t)
    return out


def _to_sound(samples):
    arr = array.array("h", (int(max(-1.0, min(1.0, s)) * 32767) for s in samples))
    return pygame.mixer.Sound(buffer=arr.tobytes())


@functools.lru_cache(maxsize=None)
def _note(freq, dur, vol, wave, decay):
    return tuple(_synth(dur, lambda p: freq, vol, wave, decay))


def _arp(notes, d, wave, vol):
    return _cat(*[_note(f, d, vol, wave, 3.0) for f in notes])


class Audio:
    def __init__(self):
        self.ok = False
        self.sfx: dict[str, pygame.mixer.Sound] = {}
        self.music: pygame.mixer.Sound | None = None
        self.music_on = True
        self.channel = None
        try:
            pygame.mixer.quit()
            pygame.mixer.init(SR, -16, 1, 512, allowedchanges=0)
            pygame.mixer.set_num_channels(20)
            pygame.mixer.set_reserved(1)
            self.ok = True
        except Exception as exc:
            print(f"[audio] disabled: {exc}")
        if self.ok:
            try:
                self._build()
            except Exception as exc:
                print(f"[audio] build failed: {exc}")
                self.ok = False

    def _build(self):
        S = self.sfx
        S["click"] = _to_sound(_synth(0.05, lambda p: 1100 - 300 * p, 0.22, "square", 7))
        S["error"] = _to_sound(_synth(0.22, lambda p: 160 - 60 * p, 0.35, "saw", 3))
        S["shoot"] = _to_sound(_mix(_synth(0.2, lambda p: 2000 * (1 - p) + 250 * p, 0.3, "square", 5),
                                    _noise(0.1, 0.15, 6, 0.6, 0.2)))
        S["boom"] = _to_sound(_mix(_noise(0.6, 0.7, 3.5), _synth(0.5, lambda p: 110 - 70 * p, 0.5, "sine", 4)))
        S["hit"] = _to_sound(_mix(_noise(0.7, 0.8, 3.0, 0.25, 0.02),
                                  _synth(0.6, lambda p: 90 - 55 * p, 0.7, "sine", 3),
                                  _synth(0.25, lambda p: 300 - 200 * p, 0.3, "saw", 6)))
        S["levelup"] = _to_sound(_arp([523.25, 659.25, 783.99, 1046.5, 1318.5], 0.09, "tri", 0.35))
        S["heal"] = _to_sound(_synth(0.35, lambda p: 500 + 800 * p, 0.3, "sine", 2))
        S["emp"] = _to_sound(_mix(_noise(0.8, 0.5, 2.5, 0.5, 0.05),
                                  _synth(0.7, lambda p: 150 + 1800 * p * p, 0.3, "saw", 2.5)))
        S["spawn"] = _to_sound(_synth(0.09, lambda p: 420 + 380 * p, 0.14, "sine", 3))
        S["combo"] = _to_sound(_arp([880, 1174.66, 1567.98], 0.07, "square", 0.2))
        S["gameover"] = _to_sound(_arp([392, 311.13, 261.63, 196, 130.81], 0.22, "saw", 0.3))
        for snd in S.values():
            snd.set_volume(0.6)
        self.music = self._build_music()
        self.channel = pygame.mixer.Channel(0)
        self.channel.set_volume(0.32)
        self.channel.play(self.music, loops=-1)

    def _build_music(self):
        bpm = 122
        step = 60 / bpm / 2
        steps = 32
        total = int(SR * step * steps)
        buf = [0.0] * total
        bass_f = [110.0, 87.31, 130.81, 98.0]
        chords = [[220, 261.63, 329.63], [174.61, 220, 261.63], [261.63, 329.63, 392], [196, 246.94, 293.66]]
        kick = _synth(0.16, lambda p: 150 - 105 * p, 0.5, "sine", 6)
        hat = _synth(0.05, lambda p: 0, 0.1, "noise", 8)

        def add(start, snd):
            for i, v in enumerate(snd):
                idx = start + i
                if idx >= total:
                    break
                buf[idx] += v

        for s in range(steps):
            bar, bi = s // 8, s % 8
            start = int(s * step * SR)
            add(start, _note(bass_f[bar], step * 0.95, 0.2, "tri", 2.0))
            f = chords[bar][(0, 1, 2, 1)[bi % 4]] * (2 if bi >= 4 else 1)
            add(start, _note(f, step * 0.9, 0.07, "square", 5.0))
            if bi % 2 == 0:
                add(start, kick)
            else:
                add(start, hat)
        return _to_sound(buf)

    def play(self, name):
        if self.ok and name in self.sfx:
            self.sfx[name].play()

    def toggle_music(self):
        self.music_on = not self.music_on
        if self.ok and self.channel:
            self.channel.set_volume(0.32 if self.music_on else 0.0)


