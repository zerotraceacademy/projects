def main():
    video_id = VIDEO_ID
    draw_loading()
    audio = Audio()
    game = Game(audio)
    world = pygame.Surface((GAME_W, HEIGHT)).convert()

    threading.Thread(target=youtube_chat_worker, args=(video_id,), daemon=True).start()

    running = True
    while running:
        dt = min(0.05, clock.tick(FPS) / 1000.0)

        for event in pygame.event.get():
            if event.type == pygame.QUIT:
                running = False
            elif event.type == pygame.KEYDOWN:
                k = event.key
                if k == pygame.K_TAB:
                    game.demo_spawn()
                elif k == pygame.K_F2:
                    game.auto_demo = not game.auto_demo
                elif k == pygame.K_F3:
                    audio.toggle_music()
                elif k == pygame.K_F11:
                    pygame.display.toggle_fullscreen()
                elif k == pygame.K_BACKSPACE:
                    game.backspace()
                elif k == pygame.K_ESCAPE:
                    game.typed = ""
                elif k in (pygame.K_RETURN, pygame.K_KP_ENTER):
                    if game.state == "gameover":
                        game.reset()
                else:
                    ch = event.unicode.lower()
                    if len(ch) == 1 and "a" <= ch <= "z":
                        game.on_char(ch)

        game.update(dt)
        game.draw(screen, world)
        pygame.display.flip()

    stop_event.set()
    pygame.quit()
    sys.exit()


if __name__ == "__main__":
    main()