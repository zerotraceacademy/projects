def extract_video_id(text: str) -> str:
    text = (text or "").strip()
    if re.fullmatch(r"[A-Za-z0-9_-]{11}", text):
        return text
    m = re.search(r"(?:v=|youtu\.be/|/live/|/embed/)([A-Za-z0-9_-]{11})", text)
    return m.group(1) if m else ""


def clean_name(raw: str) -> str:
    """The game font can't draw emoji / Hindi etc, so keep plain ASCII."""
    name = "".join(ch for ch in raw if 32 <= ord(ch) < 127).strip()
    if len(name) < 2:
        name = "Viewer%03d" % (zlib.crc32(raw.encode("utf-8", "ignore")) % 1000)
    return name[:12]


def parse_attack(message: str) -> str | None:
    for tok in re.split(r"[\s,.;:]+", message.lower()):
        tok = tok.lstrip("!/#@").rstrip("!?")
        if tok in ALLOWED_SET:
            return tok
    return None


