def lerp(a: float, b: float, t: float) -> float:
    return a + (b - a) * t


def lerp_color(c1, c2, t):
    t = max(0.0, min(1.0, t))
    return (int(lerp(c1[0], c2[0], t)), int(lerp(c1[1], c2[1], t)), int(lerp(c1[2], c2[2], t)))


def scale_color(c, m):
    m = max(0.0, m)
    return (min(255, int(c[0] * m)), min(255, int(c[1] * m)), min(255, int(c[2] * m)))


_glow_sprites: dict = {}


def glow_sprite(radius: float, color) -> pygame.Surface:
    """Radial gradient on black. Blit it with BLEND_RGB_ADD to get a glow."""
    radius = max(4, int(radius) // 4 * 4)
    color = (color[0] // 16 * 16, color[1] // 16 * 16, color[2] // 16 * 16)
    key = (radius, color)
    spr = _glow_sprites.get(key)
    if spr is None:
        spr = pygame.Surface((radius * 2, radius * 2)).convert()
        spr.fill((0, 0, 0))
        for i in range(radius, 0, -1):
            t = (1 - i / radius) ** 2.2
            pygame.draw.circle(spr, (int(color[0] * t), int(color[1] * t), int(color[2] * t)), (radius, radius), i)
        _glow_sprites[key] = spr
    return spr


def blit_glow(target: pygame.Surface, center, radius: float, color) -> None:
    spr = glow_sprite(radius, color)
    half = spr.get_width() // 2
    target.blit(spr, (int(center[0]) - half, int(center[1]) - half), special_flags=pygame.BLEND_RGB_ADD)


_text_cache: dict = {}


def _text_surface(text: str, font: pygame.font.Font, color, glow: int):
    key = (text, id(font), color, glow)
    hit = _text_cache.get(key)
    if hit is not None:
        return hit
    if len(_text_cache) > 1500:
        _text_cache.clear()
    base = font.render(text, True, color)
    if not glow:
        res = (base, 0)
    else:
        pad = 10
        w, h = base.get_size()
        big = pygame.Surface((w + 2 * pad, h + 2 * pad), pygame.SRCALPHA)
        big.blit(base, (pad, pad))
        small = pygame.transform.smoothscale(big, (max(1, big.get_width() // 4), max(1, big.get_height() // 4)))
        blur = pygame.transform.smoothscale(small, big.get_size())
        out = pygame.Surface(big.get_size(), pygame.SRCALPHA)
        for _ in range(glow + 1):
            out.blit(blur, (0, 0))
        out.blit(base, (pad, pad))
        res = (out, pad)
    _text_cache[key] = res
    return res


def draw_text(surf, text, font, color, pos, anchor="topleft", glow=0):
    s, pad = _text_surface(text, font, color, glow)
    r = pygame.Rect((0, 0), font.size(text))
    setattr(r, anchor, pos)
    surf.blit(s, (r.x - pad, r.y - pad))
    return r


def make_vignette(color, max_alpha, power=2.2):
    small = pygame.Surface((64, 36), pygame.SRCALPHA)
    for y in range(36):
        for x in range(64):
            dx = (x / 63 - 0.5) * 2
            dy = (y / 35 - 0.5) * 2
            d = min(1.0, math.sqrt(dx * dx + dy * dy) / 1.35)
            small.set_at((x, y), (*color, int(max_alpha * d ** power)))
    return pygame.transform.smoothscale(small, (GAME_W, HEIGHT))


