class Spark:
    __slots__ = ("x", "y", "vx", "vy", "life", "max", "size", "color", "drag", "grav")

    def __init__(self, x, y, vx, vy, life, size, color, drag=1.5, grav=0.0):
        self.x, self.y, self.vx, self.vy = x, y, vx, vy
        self.life = self.max = life
        self.size, self.color, self.drag, self.grav = size, color, drag, grav

    def update(self, dt):
        self.life -= dt
        f = max(0.0, 1 - self.drag * dt)
        self.vx *= f
        self.vy = self.vy * f + self.grav * dt
        self.x += self.vx * dt
        self.y += self.vy * dt


class Fragment:
    """A letter of a destroyed word, flying apart & spinning."""
    __slots__ = ("surf", "x", "y", "vx", "vy", "angle", "spin", "life", "max")

    def __init__(self, surf, x, y):
        self.surf, self.x, self.y = surf, x, y
        a = random.uniform(-math.pi, 0)
        v = random.uniform(120, 380)
        self.vx, self.vy = math.cos(a) * v, math.sin(a) * v
        self.angle = random.uniform(0, 360)
        self.spin = random.uniform(-540, 540)
        self.life = self.max = random.uniform(0.7, 1.2)

    def update(self, dt):
        self.life -= dt
        self.vy += 700 * dt
        self.x += self.vx * dt
        self.y += self.vy * dt
        self.angle += self.spin * dt


